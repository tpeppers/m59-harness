import assert from 'node:assert/strict';
import {mkdtempSync,rmSync,mkdirSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {readIntent,setIntent,planInventory,saleBlocked} from './m59-inventory-intent.mjs';
import {readVaultPlan,packCapacity,remainingCapacity,storageViewerText} from './m59-inventory-storage.mjs';
import {checkedChange,encode} from './m59-inventory-intent-service.mjs';
import {checkedEquip,equipOnce} from './m59-inventory-equip.mjs';
const dir=mkdtempSync(join(tmpdir(),'m59-storage-intent-test-'));
const identity={server:'fixture.invalid:5959',account:'fixture',character:'Fixture',player_id:17};
const item={id:31,name:'long sword',amount:1,recommended:true,actions:['use'],equipped:false,role:'weapon'};
const now=Date.now();
try {
  let doc=setIntent(identity,item,{dir,state:'vault',revision:0});
  assert.equal(doc.intents[31].state,'keep');assert.equal(planInventory([item],doc)[0].purpose,'vault');
  assert.match(saleBlocked({credentials:{host:'fixture.invalid',port:5959,account:'fixture'},client:{me:{name:'Fixture',id:17}}},item,{dir}),/veto/);
  doc=setIntent(identity,item,{dir,state:'equipment',revision:1});assert.equal(doc.revision,2);
  assert.equal(setIntent(identity,item,{dir,state:'sell',source:'ai'}).revision,2);
  const p={agent:'t1',identity,room:39,room_wire:{room_resource_id:22,room_security_u32:33},at:now,revision:2,items:planInventory([item],doc)};
  const row={agent:'t1',character:'Fixture',snapshot_age_ms:1,pack:{max:2000}};
  assert.equal(packCapacity({...p,items:[]},row).weight,0);assert.equal(remainingCapacity(packCapacity({...p,items:[]},row)),1);
  assert.equal(remainingCapacity({max:2000,weight:500,bulk:2000,exact:true}),0);
  assert.equal(remainingCapacity({max:2000,weight:9999,bulk:500,exact:true},'vault'),.75);
  assert.equal(remainingCapacity({max:2000,weight:0,bulk:0,exact:false}),null);
  assert.equal(packCapacity(p,{...row,character:'Other'}),null);
  const vaultRoot=join(dir,'substrate/storage/vaults');mkdirSync(vaultRoot,{recursive:true});
  const path=join(vaultRoot,'Fixture.json');
  writeFileSync(path,JSON.stringify({character:'Fixture',observed_at:now-1000,items:[{name:'long sword',amount:3}]}));
  p.vault=readVaultPlan(dir,identity,doc,now);assert.equal(p.vault.items[0].amount,3);
  const change={fleet:'test',broker_pid:77,agent:'t1',character:'Fixture',player_id:17,clicked_at:now,
    revision:2,item_id:1,item_name:'long sword',location:'vault',state:'withdraw',source:'operator',vault_key:p.vault.key,vault_at:p.vault.at};
  assert.equal(checkedChange([p],change,{fleet:'test',broker_pid:77},{dir,now}).state,'withdraw');
  doc=readIntent(identity,{dir});p.revision=doc.revision;p.vault=readVaultPlan(dir,identity,doc,now);
  assert.equal(p.vault.items[0].purpose,'withdraw');
  assert.throws(()=>checkedChange([p],{...change,revision:3,vault_key:'b'.repeat(64)},{fleet:'test',broker_pid:77},{dir,now}));
  const wire=storageViewerText([p],{fleet:'test',broker_pid:77,now},encode);assert.match(wire,/M59SELLPLAN\t2/);assert.match(wire,/\nJ\tt1\t1\tlong%20sword\t3/);
  const equip={...change,revision:3,item_id:31,location:'pack',state:'equip'};
  const target=checkedEquip([p],equip,{fleet:'test',broker_pid:77},{dir,now});
  assert.throws(()=>checkedEquip([{...p,paused:true}],equip,{fleet:'test',broker_pid:77},{dir,now}));
  assert.throws(()=>checkedEquip([p],{...equip,source:'ai'},{fleet:'test',broker_pid:77},{dir,now}));
  let equipped=false;const calls=[];
  const rpc=async(name,args)=>{calls.push([name,args]);if(name==='commander_lease')return args.action==='acquire'?{lease_token:'fixture-lease'}:{released:true};
    if(args.action==='item_use')equipped=true;return {accepted:true};};
  const result=await equipOnce(target,{fleet:'test',broker_pid:77},{rpc,sleep:async()=>{},currentPlan:()=>({...p,items:p.items.map(i=>({...i,equipped}))})});
  assert.equal(result.equipped,true);assert.deepEqual(calls.map(c=>c[1].action),['acquire','stand','item_use','release']);
  assert.equal(calls[2][1].expected_item_name,'long sword');
  calls.length=0;await assert.rejects(equipOnce(target,{fleet:'test',broker_pid:77},{rpc,sleep:async()=>{},currentPlan:()=>null}));
  assert.equal(calls.at(-1)[1].action,'release');
  console.log('Storage/equip tests passed: capacity, cached vault identity, cross-location IDs, protected intentions, AI veto, authenticated explicit equip, lease release');
}finally {rmSync(dir,{recursive:true,force:true});}
