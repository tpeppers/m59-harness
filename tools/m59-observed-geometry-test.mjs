import assert from 'node:assert/strict';
import {roomGeometry} from './m59-ground.mjs';
import {loadMap} from './m59-map.mjs';
import {copyFineGeometry,applyFineSectorObservations} from './m59-observed-geometry.mjs';
import {findFineGuide} from './m59-fine-guides.mjs';
import {protocolToClient} from './m59-finepos.mjs';
import {doorStateForGeometry} from './m59-routes.mjs';
const source=roomGeometry(2505),first=copyFineGeometry(source),other=copyFineGeometry(source),map=loadMap();
const from=protocolToClient({x:3936,y:416}),to=protocolToClient({x:4128,y:1760});
const route=g=>findFineGuide(g,from,to,{edge:(a,b)=>{const t=g.traceFineMoveClient(a.x,a.y,b.x,b.y,{slide:false});return t.arrived&&!t.blocked;}});
assert.equal(route(source),null);assert.equal(route(first),null);
applyFineSectorObservations(map,2505,first,{1:{height:1150,type:5,speed:50,at:100}});
assert(route(first)?.ok,'the observed open ceiling admits the return guide in the external planner');
assert.equal(route(source),null,'the baked source stays closed');
assert.equal(route(other),null,'another character does not inherit this door replay');
applyFineSectorObservations(map,2505,first,{1:{height:1060,type:5,speed:50,at:10000}});
assert.equal(route(first),null,'a later close invalidates the route');
applyFineSectorObservations(map,2505,first,{1:{height:1150,type:4,speed:50,at:11000}});
assert.equal(route(first),null,'a floor event must not masquerade as an opened ceiling');
console.log('External fine geometry follows typed open/close observations without mutating the baked map or another character.');
{
 const cave=roomGeometry(27),a=copyFineGeometry(cave),b=copyFineGeometry(cave),closed=Buffer.from(cave._stepMask);
 const open=Object.fromEntries([1,2,3,4,5].map(id=>[id,{height:24,type:4,speed:0,at:100}]));
 applyFineSectorObservations(map,27,a,open);
 assert(!Buffer.from(a._stepMask).equals(closed),'the actual five-sector Dispel state changes the cave mask');
 applyFineSectorObservations(map,27,b,open);
 assert.equal(doorStateForGeometry(a).applied,true);assert.equal(doorStateForGeometry(b).applied,true);
 assert(Buffer.from(a._stepMask).equals(Buffer.from(b._stepMask)),'a second courier must receive the open mask even when another copy already published that state');
 const c=copyFineGeometry(a);c.attachStepMask(closed);
 assert.equal(doorStateForGeometry(c).applied,false);
 applyFineSectorObservations(map,27,c,open);
 assert(Buffer.from(a._stepMask).equals(Buffer.from(c._stepMask)),'matching heights cannot excuse a stale closed mask');
 assert(Buffer.from(cave._stepMask).equals(closed),'the original baked cave remains unmodified');
 const ceiling=Object.fromEntries([1,2,3,4,5].map(id=>[id,{height:24,type:5,speed:0,at:200}]));
 applyFineSectorObservations(map,27,b,ceiling);
 assert(Buffer.from(b._stepMask).equals(closed),'ceiling events cannot open a floor gate');
}
