import assert from 'node:assert/strict';
import {roomGeometry} from './m59-ground.mjs';
import {planFineSafeLeg,normalizeSafeLegPolicy,legWalls} from './m59-safelegs.mjs';
import {validateEscape,planRailDeparture} from './m59-pocket-rails.mjs';
import {loadMap} from './m59-map.mjs';
import {routesFor,attachStepMasks} from './m59-routes.mjs';
import {RoomGeometry} from './m59-roo.mjs';
import {applyCeilingDoors} from './m59-ceiling-doors.mjs';
import {planFineRailRefugeAsync,cutFineRailAsync} from './m59-fine-rail.mjs';
import {sessionWalkPrototype} from './m59-session-walk.mjs';
const map=loadMap();attachStepMasks(map);const table=routesFor(map.geometryManifestSha256);
// Actual Ugol wall departure: the square graph calls it seven steps, but the
// body must leave south, cross west, then go north around the ledge.
const geo=roomGeometry(2500),from={x:2608,y:2352},target={row:29,col:36};
const plan=planFineSafeLeg(geo,from,target,{maxLeg:14});
assert.equal(plan.found,true,JSON.stringify(plan));
assert(plan.steps<=14);
assert.notDeepEqual({row:plan.row,col:plan.col},target);
assert(legWalls(geo).some(w=>w.row===plan.row&&w.col===plan.col));
assert(validateEscape(geo,from,plan.waypoints).ok);
assert.equal(Math.floor(plan.waypoints.at(-1).x/64),plan.col);
assert.equal(Math.floor(plan.waypoints.at(-1).y/64),plan.row);
const short=planFineSafeLeg(geo,from,target,{maxLeg:3});
assert.equal(short.found,true);assert(short.steps<=3);
assert.deepEqual({row:short.row,col:short.col},{row:37,col:38});
assert.equal(planFineSafeLeg(geo,from,target,{maxLeg:0.1}).found,false);
const held=planFineSafeLeg(geo,from,target,{maxLeg:3,occupied:new Set(['37,38'])});
assert.equal(held.found,false,'an occupied wall cannot be the next refuge');
const avoid=new Set(['37,38','39,33','39,34']),avoiding=planFineSafeLeg(geo,from,target,{maxLeg:14,avoidSquares:avoid});
if(avoiding.found)assert(validateEscape(geo,from,avoiding.waypoints,{avoidSquares:avoid}).ok);
assert.equal(normalizeSafeLegPolicy({fineLegs:true}).fineLegs,true);
assert.throws(()=>normalizeSafeLegPolicy({fineLegs:'yes'}),/fineLegs must be a boolean/);
const pocket=planFineSafeLeg(geo,{x:816,y:688},{row:6,col:16},{maxLeg:14});
assert(pocket.found,JSON.stringify(pocket));assert(pocket.steps<=14);
assert(validateEscape(geo,{x:816,y:688},pocket.waypoints).ok);
const chamber=roomGeometry(2501),entry={x:416,y:3808},stage={row:31,col:2};
const departure=planRailDeparture(chamber,entry,stage,{room:2501,table});
assert(departure.found,'an inside edge stage must retain its compatible boundary rail');
assert(departure.rail.squares.at(-1).col<=2);
const corridor=planFineSafeLeg(chamber,entry,{row:56,col:31},{maxLeg:28,exitGoal:stage,table,room:2501});
assert(corridor.found,JSON.stringify(corridor));assert(corridor.steps<=28);
assert(validateEscape(chamber,entry,corridor.waypoints).ok);
const konima=RoomGeometry.fromJSON(map.rooms[2505].roo),arrival={row:6,col:59,x:3808,y:416},west={row:72,col:2};
konima.attachStepMask(roomGeometry(2505)._stepMask);
assert.equal((await planFineRailRefugeAsync(konima,arrival,west,{maxLeg:28})).found,false,'the closed gate cannot be crossed');
applyCeilingDoors(map,2505,new Map([[1,{type:5,height:1150}]]),null,{geometryOf:()=>konima});
let ticks=0;const clock=setInterval(()=>ticks++,10);
const open=await planFineRailRefugeAsync(konima,arrival,west,{maxLeg:28});clearInterval(clock);
assert(open.found,JSON.stringify(open));assert(open.steps<=28);assert(ticks>=2,'planning leaves the keeper event loop free');
assert(legWalls(konima).some(w=>w.row===open.row&&w.col===open.col));
assert(validateEscape(konima,arrival,open.waypoints).ok,'every pulled packet retains the ordinary mover proof');
const cancelled=await planFineRailRefugeAsync(konima,arrival,west,{maxLeg:28},{cancelled:()=>true});
assert.equal(cancelled.cancelled,true);
let cancelInFlight=false;const cancelTimer=setTimeout(()=>{cancelInFlight=true;},30);
const cancelledWorker=await planFineRailRefugeAsync(konima,arrival,west,{maxLeg:28},{cancelled:()=>cancelInFlight});clearTimeout(cancelTimer);
assert.equal(cancelledWorker.cancelled,true,'an in-flight worker cancellation returns without terminating its isolate');
const fineCut=await cutFineRailAsync(konima,arrival,{x:160,y:4640});
assert(fineCut.ok&&fineCut.bridgeOk,JSON.stringify({...fineCut,waypoints:fineCut.waypoints?.length}));
assert(fineCut.waypoints.length>2);assert.equal(fineCut.waypoints[0].x,(arrival.x-64)*16);
const merb=roomGeometry(2503),merbBody={row:69,col:76,x:4880,y:4416},merbGoal={row:57,col:2};
assert.equal((await planFineRailRefugeAsync(merb,merbBody,merbGoal,{maxLeg:14})).found,false,'Merb needs its measured per-room gap allowance');
const wide=await planFineRailRefugeAsync(merb,merbBody,merbGoal,{maxLeg:28});
assert(wide.found,JSON.stringify(wide));assert(wide.steps<=28);assert.equal(wide.row,68);assert.equal(wide.col,49);
assert(validateEscape(merb,merbBody,wide.waypoints).ok,'a refuge beyond the local search window retains a full mover proof');
// Ugol's coarse targets sent the body around a cycle of different ledges.
// Exercise the actual executor against real geometry with a proved packet seam.
const client={self:{row:27,col:20,x:1320,y:1744},room:{id:2500,objects:new Map(),flags:0},me:{name:'offline Ugol'}};
const executor={client,need:()=>client,world:{room:map.rooms[2500],geometry:geo,map},movementGeneration:0,
  movementWasCancelled:()=>false,threatsHere:()=>[],walkDepartureLegs:async(points)=>{
    assert(validateEscape(geo,client.self,points).ok,'each forward packet must retain the ordinary mover proof');
    const p=points.at(-1);Object.assign(client.self,p,{row:Math.floor(p.y/64),col:Math.floor(p.x/64)});return {arrived:true};
  }};
const forward=await sessionWalkPrototype({}).crossBySafeLegs.call(executor,{stand_on:{row:1,col:27},to:2501},
  {policy:{rooms:[2500],required:true,fineLegs:true,maxLeg:14}});
assert(forward.handed_over,JSON.stringify(forward));assert(forward.legs<=6);
assert.equal(client.self.row,1);assert.equal(client.self.col,27);assert.equal(new Set(forward.walls).size,forward.walls.length);
const konimaWest=roomGeometry(2505),westBody={row:9,col:79,x:5112,y:576},wrongStage={row:73,col:2};
const alternate=await planFineRailRefugeAsync(konimaWest,westBody,wrongStage,{maxLeg:20,
  goalFine:{x:96,y:4704},goalFineAlternates:[{x:96,y:4688}]});
assert(alternate.found,JSON.stringify(alternate));assert(alternate.steps<=20);
assert(validateEscape(konimaWest,westBody,alternate.waypoints).ok);
const opening=await planFineRailRefugeAsync(konimaWest,{row:72,col:2,x:160,y:4640},wrongStage,
  {maxLeg:14,goalFine:{x:96,y:4688}});
assert.equal(opening.kind,'exit',JSON.stringify(opening));assert.deepEqual(opening.waypoints.at(-1),{x:96,y:4688});
const eastWall={row:26,col:95,x:6128,y:1720};
assert.equal((await planFineRailRefugeAsync(konimaWest,eastWall,wrongStage,{maxLeg:20,goalFine:{x:96,y:4688}})).found,false);
const eastGap=await planFineRailRefugeAsync(konimaWest,eastWall,wrongStage,{maxLeg:28,goalFine:{x:96,y:4688}});
assert(eastGap.found,JSON.stringify(eastGap));assert(eastGap.steps>20&&eastGap.steps<=28);
assert(validateEscape(konimaWest,eastWall,eastGap.waypoints).ok);
const obfal=roomGeometry(2504),obfalBody={row:37,col:22,x:1464,y:2400},obfalExit={row:81,col:62},obfalOptions={goalFine:{x:3984,y:5280},goalFineAlternates:[{x:4000,y:5280},{x:4072,y:5280},{x:4064,y:5280},{x:4128,y:5280}]};
assert.equal((await planFineRailRefugeAsync(obfal,obfalBody,obfalExit,{...obfalOptions,maxLeg:28})).found,false);
const obfalGap=await planFineRailRefugeAsync(obfal,obfalBody,obfalExit,{...obfalOptions,maxLeg:36});
assert(obfalGap.found&&obfalGap.steps>28&&obfalGap.steps<=36,JSON.stringify(obfalGap));
assert(validateEscape(obfal,obfalBody,obfalGap.waypoints).ok);
const merbNorthWall={row:60,col:77,x:4928,y:3880},merbFineExit={goalFine:{x:96,y:3680},goalFineAlternates:[{x:96,y:3724},{x:96,y:3744},{x:96,y:3799}]};
assert.equal((await planFineRailRefugeAsync(merb,merbNorthWall,merbGoal,{...merbFineExit,maxLeg:28})).found,false);
const merbLongGap=await planFineRailRefugeAsync(merb,merbNorthWall,merbGoal,{...merbFineExit,maxLeg:36});
assert(merbLongGap.found&&merbLongGap.steps>28&&merbLongGap.steps<=36,JSON.stringify(merbLongGap));
assert(validateEscape(merb,merbNorthWall,merbLongGap.waypoints).ok);
console.log('Fine safe legs stop on collision-proved refuges within the actual distance allowance.');
