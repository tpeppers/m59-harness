import assert from 'node:assert/strict';
import {islandTaskSteps,script as trip} from './fleetscripts/island-trip.mjs';
import {script as bows} from './fleetscripts/island-bows.mjs';
import {script as home} from './fleetscripts/island-home.mjs';
import {applyDefaults} from './m59-fleetlib.mjs';
import {sessionWalkPrototype} from './m59-session-walk.mjs';
const p=applyDefaults(trip,{agent:'courier',agents:['courier']});
let received;
const scripts=new Map([['work',{steps:async args=>{received=args;return [{do:'verify',fn:()=>true}];}}]]);
assert.equal((await islandTaskSteps({...p,task:'work',taskParams:'{"agents":["foreign"],"minHealth":0}'},{scripts})).length,1);
assert.deepEqual(received.agents,['courier']);assert.equal(received.minHealth,1);
assert.equal(received.fragileBelow,20);
await assert.rejects(islandTaskSteps({...p,task:'absent'},{scripts}),/invalid island task/);
scripts.set('unsafe',{unsafe:{waives:['journeyHealth']},steps:async()=>[]});
await assert.rejects(islandTaskSteps({...p,task:'unsafe'},{scripts}),/waive/);
await assert.rejects(islandTaskSteps({...p,task:'work',taskParams:'[]'},{scripts}),/JSON object/);
const steps=await trip.steps({...p,task:'island-bows',taskParams:'{"bows":2,"arrows":200}'});
assert.equal(steps[0].do,'verify');
assert(steps.some(s=>s.do==='shop'&&s.seller==="Hanla zax'Ta"));
assert(steps.some(s=>s.do==='shop'&&s.seller==="Kochtal ko'Tulca"&&s.lines[0].match.test('practice bow')));
assert.equal(steps.at(-1).to,52);
assert.equal(home.params.requireSafeLegs.default,true);
assert.equal(trip.params.destination.default,2001);
const walking=await trip.steps({...p,outbound:'walk'});
assert.equal(walking[0].to,27);assert(!walking[0].avoid.includes(587));
assert(walking.some(s=>s.do==='walk'&&s.to===2001));
// The pool-of-vigor drink (a no-op outside 2510) comes before the first walk, which is still to the island (2000).
{const hs=await home.steps({...p});assert.equal(hs[0].do,'verify');assert.equal(hs[0].optional,true);assert.equal(hs.find(s=>s.do==='walk').to,2000);}
const convoy=await trip.steps({...p,outbound:'walk',agents:['a','b']});
assert.equal(convoy[0].do,'verify');assert.equal(convoy.at(-1).always,true);
assert.equal(trip.params.departSpacingMs.default,60000);
await assert.rejects(trip.steps({...p,departSpacingMs:-1}),/convoy timing/);
assert(!steps.at(-1).avoid.includes(587));
await assert.rejects(bows.steps({bows:-1,arrows:1}),/nonnegative/);
const maximum=await bows.steps({bows:1,arrows:200,bowType:'practice',maxBows:true});
assert.equal(maximum[0].to,2100,'reserve the requested arrows before filling the remaining bow budget');
assert(maximum.some(s=>s.do==='walk'&&s.to===2014));
assert.equal(maximum.at(-1).to,2000);
await assert.rejects(bows.steps({bows:1,arrows:200,bowType:'long',maxBows:true}),/practice/);
// Required routing refuses missing geometry; ordinary travel retains its default.
const prototype=sessionWalkPrototype({}), fake={need:()=>({}),world:{room:{num:99},geometry:null}};
assert.equal((await prototype.crossBySafeLegs.call(fake,{stand_on:{row:1,col:1}},{policy:{rooms:[99],required:true}})).refused,true);
assert.equal(await prototype.crossBySafeLegs.call(fake,{stand_on:{row:1,col:1}},{policy:{rooms:[99]}}),null);
const unlocated={...fake,movementWasCancelled:()=>false,world:{room:{num:99},geometry:{collisionReady:true}}};
assert.equal((await prototype.crossBySafeLegs.call(unlocated,{stand_on:{row:1,col:1}},{policy:{rooms:[99],required:true}})).refused,true);
