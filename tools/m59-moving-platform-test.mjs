import assert from 'node:assert/strict';
import {roomGeometry,floorAt} from './m59-ground.mjs';
import {applyAncientFloors,liftWaitMs} from './m59-moving-platform.mjs';
import {traceFallMotion} from './m59-falltrace.mjs';
const geo=roomGeometry(579),map={rooms:{579:{}}};
const apply=(heights,event=null,now=1000)=>applyAncientFloors(map,579,new Map(Object.entries(heights).map(([id,height])=>[Number(id),{height,type:4}])),event,{geometryOf:()=>geo,now});
assert.equal(liftWaitMs(),37667);
assert.throws(()=>liftWaitMs({speed:0}));
assert.equal(applyAncientFloors(map,578,new Map()),null);
const shipped=floorAt(geo,55808,25088);
apply({2:250,3:250,4:540,9:510});
assert.equal(floorAt(geo,55808,25088),4000);
const jump=(a,b)=>traceFallMotion(geo,55808,a,55808,b);
assert.equal(jump(32000,25088).arrived,true);
assert.equal(jump(14848,7680).arrived,false,'north fall is impossible from lowered lift');
const rising=apply({2:800,3:800,4:510,9:540},{sector:3,type:4,height:800,speed:15});
assert.equal(rising.settledAt,38667);
assert(rising.sectorIndices.includes(72));
assert.equal(floorAt(geo,55808,25088),12800);
assert.equal(jump(14848,7680).arrived,true);
assert.equal(jump(32000,25088).arrived,false,'cannot board a raised lift from the south');
const lowering=apply({2:250,3:250,4:540,9:510},{sector:3,type:4,height:250,speed:15},50000);
assert.equal(lowering.settledAt,87667);
apply({});
assert.equal(floorAt(geo,55808,25088),shipped,'room entry restores original baseline before replay');
assert.equal(jump(14848,7680).arrived,false);
console.log('moving platform: 15 checks passed');
